import * as fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  renderSchemeRecipe,
  validateToneScheme,
} from '../packages/diagram-gen/src/tone-context.mjs';
import { validateMaterializationKit } from '../packages/diagram-gen/src/materialize.mjs';

const root = fileURLToPath(new URL('../packages/diagram-gen/tones/', import.meta.url));
const pilots = new Set(['fine-outline', 'soft-fill', 'paper-layers', 'pencil-notebook']);
const xml = (value) =>
  String(value)
    .replaceAll('&', '&amp;')
    .replaceAll('"', '&quot;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;');

export function compileAuthoringTemplate(template, scheme) {
  validateToneScheme(scheme);
  let result = template.replace(/\{\{palette:([A-Za-z]+)\}\}/g, (_, role) => {
    if (!Object.hasOwn(scheme.palette.light, role))
      throw new Error(`Unknown palette role ${role}.`);
    return scheme.palette.light[role];
  });
  result = result.replace(/\{\{font:([A-Za-z]+)\}\}/g, (_, role) => {
    if (!Object.hasOwn(scheme.typography, role))
      throw new Error(`Unknown typography role ${role}.`);
    return xml(scheme.typography[role].fontFamily);
  });
  result = renderSchemeRecipe(result, scheme);
  if (/\{\{|\}\}/.test(result)) throw new Error('Unresolved rollout authoring placeholder.');
  return result;
}

export function compileRolloutKit(template, scheme) {
  const result = compileAuthoringTemplate(template, scheme);
  validateMaterializationKit(result, scheme);
  return result.replace(
    '<svg ',
    '<!-- Generated by scripts/build-rollout-kits.mjs; edit kit.template.svg and scheme.json. -->\n<svg ',
  );
}

export async function buildRolloutKits({ toneRoot = root, tones, check = false } = {}) {
  const catalog = JSON.parse(await fs.readFile(path.join(toneRoot, 'catalog.json'), 'utf8'));
  const ids = catalog.tones.map(({ id }) => id).filter((id) => !pilots.has(id));
  const selected = tones ?? ids;
  if (
    !Array.isArray(selected) ||
    new Set(selected).size !== selected.length ||
    selected.some((id) => !ids.includes(id))
  )
    throw new Error(
      'Select unique existing non-pilot tone IDs. Accepted pilot resources are frozen.',
    );
  for (const id of selected) {
    const directory = path.join(toneRoot, id);
    const scheme = JSON.parse(await fs.readFile(path.join(directory, 'scheme.json'), 'utf8'));
    validateToneScheme(scheme, { toneId: id, collectionVersion: catalog.version });
    const compiled = compileRolloutKit(
      await fs.readFile(path.join(directory, 'kit.template.svg'), 'utf8'),
      scheme,
    );
    const output = path.join(directory, 'kit.svg');
    if (check) {
      if ((await fs.readFile(output, 'utf8')) !== compiled)
        throw new Error(`${id}: kit differs from its authoritative scheme/template.`);
    } else await fs.writeFile(output, compiled);
  }
  return selected;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  let check = false,
    tone;
  for (let i = 0; i < args.length; i++) {
    if (args[i] === '--check' && !check) check = true;
    else if (
      args[i] === '--tone' &&
      tone === undefined &&
      args[i + 1] &&
      !args[i + 1].startsWith('--')
    )
      tone = args[++i];
    else throw new Error('Usage: node scripts/build-rollout-kits.mjs [--check] [--tone ID]');
  }
  const ids = await buildRolloutKits({ check, ...(tone ? { tones: [tone] } : {}) });
  console.log(
    `${ids.length} rollout kits ${check ? 'verified' : 'generated'}; actual visual acceptance remains separate.`,
  );
}
