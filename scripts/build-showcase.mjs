import { readdir, mkdir, readFile, writeFile, unlink } from 'node:fs/promises';
import { resolve, join, dirname, relative } from 'node:path';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { loadSession, loadToneCatalog } from '../packages/diagram-gen/src/model.mjs';
import { createPageSource } from '../packages/diagram-gen/src/render.mjs';

export const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const links = { homeUrl:'/', docsUrl:'/docs/getting-started/introduction/', catalogUrl:'/docs/tones/' };
let generated = {};
const digest = content => createHash('sha256').update(content).digest('hex');
async function writeIfChanged(file, content) {
  generated[relative(projectRoot,file)] = digest(content);
  try { if (await readFile(file, 'utf8') === content) return; } catch (error) { if (error.code !== 'ENOENT') throw error; }
  await mkdir(dirname(file), {recursive:true});
  await writeFile(file, content);
}
export async function buildShowcase() {
  generated = {};
  const manifestPath = join(projectRoot,'.generated/showcase-files.json');
  let previous = {};
  try { previous = JSON.parse(await readFile(manifestPath,'utf8')); } catch(error) { if(error.code!=='ENOENT') throw error; }
  const catalog = await loadToneCatalog();
  await writeIfChanged(join(projectRoot,'pages/tones.tsx'), await createPageSource(catalog, links));
  const entries = (await readdir(join(projectRoot,'examples'),{withFileTypes:true})).filter(d=>d.isDirectory()).sort((a,b)=>a.name.localeCompare(b.name));
  const sessions = [];
  for (const entry of entries) {
    const data = await loadSession(join(projectRoot,'examples',entry.name));
    await writeIfChanged(join(projectRoot,'pages/examples',`${entry.name}.tsx`), await createPageSource(data, links));
    if (entry.name === 'tone-exploration') await writeIfChanged(join(projectRoot,'public/workbench-data/tone-exploration.json'),JSON.stringify({...data,links},null,2)+'\n');
    const first = data.candidates[0];
    const preview = `/previews/${entry.name}.svg`;
    if (first) await writeIfChanged(join(projectRoot,'public',preview), first.assets.light);
    sessions.push({slug:entry.name,title:data.session.title,description:data.session.description||'',candidates:data.candidates.length,rounds:data.rounds.length,preview,href:`/examples/${entry.name}/`});
  }
  sessions.sort((a,b)=>(a.slug==='tone-exploration'?-1:b.slug==='tone-exploration'?1:a.title.localeCompare(b.title)));
  const featured=[];
  for(const id of ['fine-outline','isometric-solid','cut-paper']) {
    const tone=catalog.tones.find(t=>t.id===id);
    const candidate=catalog.candidates.find(c=>c.toneId===id);
    if (!tone || !candidate) continue;
    const preview=`/previews/tone-${id}.svg`;
    await writeIfChanged(join(projectRoot,'public',preview),candidate.assets.light);
    featured.push({id,name:tone.name,number:tone.number,preview});
  }
  await writeIfChanged(join(projectRoot,'src/generated/site-data.ts'),`// Generated by scripts/build-showcase.mjs\nexport const featuredTones = ${JSON.stringify(featured,null,2)};\nexport const exampleSessions = ${JSON.stringify(sessions,null,2)};\n`);
  for(const [file,hash] of Object.entries(previous)) {
    if(file in generated) continue;
    // Only the builder's own recognized output locations may be removed.
    if(!/^(pages\/(?:examples\/[^/]+|tones|workbench)\.tsx|public\/previews\/[^/]+\.svg|public\/workbench-data\/tone-exploration\.json|src\/generated\/site-data\.ts)$/.test(file)) continue;
    try {
      const absolute=join(projectRoot,file);
      if(digest(await readFile(absolute))===hash) await unlink(absolute);
      else console.warn(`Preserved modified generated file: ${file}`);
    }catch(error){if(error.code!=='ENOENT')throw error;}
  }
  await mkdir(dirname(manifestPath),{recursive:true});
  await writeFile(manifestPath,JSON.stringify(generated,null,2)+'\n');
  return {tones:catalog.candidates.length,sessions:sessions.length,candidates:sessions.reduce((a,s)=>a+s.candidates,0)};
}
if(process.argv[1] && resolve(process.argv[1])===fileURLToPath(import.meta.url)) console.log('Prepared showcase:',await buildShowcase());
