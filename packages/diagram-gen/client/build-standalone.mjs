import { readFile, writeFile } from 'node:fs/promises';

const source = await readFile(new URL('./mount.mjs', import.meta.url), 'utf8');
const placement = (await readFile(new URL('./placement.mjs', import.meta.url), 'utf8')).replaceAll(
  'export function ',
  'function ',
);
const review = (await readFile(new URL('./review.mjs', import.meta.url), 'utf8')).replaceAll(
  'export function ',
  'function ',
);
const project = (await readFile(new URL('./project.mjs', import.meta.url), 'utf8'))
  .replace(/^import .*;\n/gm, '')
  .replaceAll('export function ', 'function ');
const classic = source
  .replace(/^import .*;\n/gm, '')
  .replace(/^export \{.*\} from .*;\n/gm, '')
  .replace('export function mountDiagramApp', 'function mountDiagramApp')
  .trimEnd();
if (classic === source) throw new Error('The mount API entrypoint was not found.');
const bootstrap = `
(() => {
  const boot = () => {
    const root = document.getElementById('diagram-app');
    const source = document.getElementById('diagram-data');
    if (!root || !source) return;
    let data;
    try {
      data = JSON.parse(source.textContent);
    } catch {
      data = { schemaVersion: 0, session: {} };
    }
    if (data.kind === 'project') mountProjectApp(root, data);
    else mountDiagramApp(root, data);
  };
  if (document.readyState === 'loading' && !document.getElementById('diagram-app'))
    document.addEventListener('DOMContentLoaded', boot, { once: true });
  else boot();
})();
`;
await writeFile(
  new URL('./app.js', import.meta.url),
  `/* Classic standalone bundle generated by build-standalone.mjs from mount.mjs. */\n${placement}\n${review}\n${classic}\n${project}${bootstrap}`,
);
